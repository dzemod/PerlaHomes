// Builds site/privacy.html: the shared header, footer, WhatsApp button and cookie banner/panel are copied
// from site/index.html (links to sections become index.html#…), the policy text comes from tools/privacy/policy-*.html.
// Run after changing the header/footer in index.html or the policy text:  node tools/build-privacy.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const index = fs.readFileSync(path.join(root, 'site/index.html'), 'utf8');
const policy = (l) => fs.readFileSync(path.join(root, `tools/privacy/policy-${l}.html`), 'utf8').trimEnd();

const cut = (from, to) => {
  const a = index.indexOf(from);
  const b = index.indexOf(to, a);
  if (a < 0 || b < 0) throw new Error(`marker not found: ${from} … ${to}`);
  return index.slice(a, b + to.length);
};
// section links → the home page; "#top" in the header logo → home; footer "Back to top" stays on this page
const toHome = (html) => html.replace(/href="#(?!top")([\w-]+)"/g, 'href="index.html#$1"');

const consentBanner = cut('<!-- Cookie banner:', '</section>');
const header = toHome(cut('<!-- ===== Header ===== -->', '</header>')).replace('<a href="#top" class="logo">', '<a href="index.html" class="logo">');
const footer = toHome(cut('<!-- ===== 10. Footer ===== -->', '</footer>'));
const wa = cut('<!-- WhatsApp -->', '</a>');
const panel = cut('<!-- Cookie settings panel', '</dialog>');

const html = `<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>Privacy and cookie policy — Perla Homes</title>
  <meta name="description" content="How Perla Homes handles personal data from the contact form and which browser storage this website uses.">
  <meta name="robots" content="noindex">
  <meta name="theme-color" content="#16302A">
  <link rel="icon" href="favicon-32.png" type="image/png" sizes="32x32">
  <link rel="apple-touch-icon" href="apple-touch-icon.png">
  <link rel="manifest" href="site.webmanifest">
  <link rel="preload" href="assets/fonts/jost-latin.woff2" as="font" type="font/woff2" crossorigin>
  <link rel="preload" href="assets/fonts/manrope-latin.woff2" as="font" type="font/woff2" crossorigin>
  <link rel="stylesheet" href="assets/css/styles.css">
</head>
<!-- GENERATED by tools/build-privacy.mjs — edit tools/privacy/policy-*.html (text) or index.html (header/footer), then rebuild. -->
<!-- TODO: policy text must be reviewed by the client's lawyer before launch. -->
<body data-page="privacy">
  <a class="skip" href="#main">Skip to content</a>

  ${consentBanner}

  ${header}

  <main id="main" class="legal-page">
    <div id="policy" lang="en">
      ${policy('en')}
    </div>
    <template data-policy="es">
      ${policy('es')}
    </template>
    <template data-policy="ru">
      ${policy('ru')}
    </template>
  </main>

  ${footer}

  ${wa}

  ${panel}

  <script src="assets/js/vendor/gsap.min.js" defer></script>
  <script src="assets/js/vendor/ScrollTrigger.min.js" defer></script>
  <script src="assets/js/main.js" defer></script>
</body>
</html>
`;
fs.writeFileSync(path.join(root, 'site/privacy.html'), html);
console.log('site/privacy.html written');
